"""config.toml -> the generated hardware headers, and the stamp that gates recalibration.

Files are only rewritten when their content changes, so editing [build] does not touch the
hardware and editing [hardware] does not trigger calibration.

usage: gen_config.py [--paths]      --paths prints output dir, calibrated file and stamp, for make
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "sw" / "compiler"))

from mini_tpu import config  # noqa: E402

BANNER = "Generated by tools/gen_config.py from config.toml. Do not edit."


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}", file=sys.stderr)


def c_header(h):
    rows = [("ARRAY_N", f"{h.array_n}u"), ("TILE_N", f"{h.tile_n}u"), ("VECTOR_LANES", f"{h.vector_lanes}u"), ("VMEM_KB", f"{h.vmem_kb}u"),
            ("MAX_K", f"{h.max_k}u"), ("MAX_LEN", f"{h.max_len}u"), ("FIFO_DEPTH", f"{h.fifo_depth}u"),
            ("CONFIG_HASH", f"0x{h.hash:016X}ull")]
    body = "".join(f"#define MINI_TPU_{k:<16}{v}\n" for k, v in rows)
    return f"// {BANNER}\n#ifndef MINI_TPU_CONFIG_H\n#define MINI_TPU_CONFIG_H\n\n{body}\n#endif\n"


def rtl_header(h):
    rows = [("ARRAY_N", h.array_n), ("VECTOR_LANES", h.vector_lanes), ("VM_AW", h.vm_aw), ("VMEM_BANKS", h.vmem_banks),
            ("MAX_K", h.max_k), ("WGT_AW", h.wgt_aw), ("MAX_LEN", h.max_len), ("FIFO_DEPTH", h.fifo_depth),
            ("FREE_W", h.free_w), ("HW_ARCH", f"32'h{h.arch_word:08X}")]
    body = "".join(f"`define MTPU_{k:<14}{v}\n" for k, v in rows)
    return f"// {BANNER}\n`ifndef MINI_TPU_CONFIG_SVH\n`define MINI_TPU_CONFIG_SVH\n\n{body}\n`endif\n"


def main():
    c = config.load()
    write(ROOT / "hw" / "interface" / "mini_tpu_config.h", c_header(c.hardware))
    write(ROOT / "hw" / "rtl" / "common" / "mini_tpu_config.svh", rtl_header(c.hardware))
    stamp = {"model": c.model_name, "seq": c.seq, "calib_tokens": c.calib_tokens}
    stamp_file = ROOT / "sw" / "compiler" / "output" / f"calib_{c.model_name}_s{c.seq}.stamp"
    write(stamp_file, json.dumps(stamp) + "\n")
    if "--paths" in sys.argv:
        print(*(p.relative_to(ROOT).as_posix() for p in (c.output, c.calibrated, stamp_file)))


if __name__ == "__main__":
    main()
