#!/usr/bin/env python3
"""Generate exp2neg.sv: e = 2^(-z) for the vector unit's VEC_SOFTMAX.

z is unsigned Q16 (z >= 0); e is unsigned Q0.16, 17 bits (1.0 = 65536).
    zr  = z + 128                 (round z to 1/256)
    I   = zr >> 16,  idx = (zr >> 8) & 0xFF
    e   = I > 16 ? 0 : LUT[idx] >> I
    LUT[i] = floor(65536 * 2^(-i/256) + 0.5)

The testbench reference model computes the same table with the same formula.
Run from this directory:  python gen_exp2neg.py > exp2neg.sv
"""
import math

lut = [math.floor(65536 * 2.0 ** (-i / 256.0) + 0.5) for i in range(256)]
assert lut[0] == 65536 and all(32768 < v <= 65536 for v in lut)

print("""`timescale 1ns/1ps

// =============================================================================
// exp2neg — e = 2^(-z) for VEC_SOFTMAX (generated by gen_exp2neg.py; do not edit)
// =============================================================================
//
// z: unsigned Q16 (z >= 0). e: unsigned Q0.16, 17 bits, 1.0 = 65536.
//   zr = z + 128; I = zr >> 16; idx = zr[15:8]
//   e  = I > 16 ? 0 : LUT[idx] >> I,   LUT[i] = floor(65536 * 2^(-i/256) + 0.5)
// Combinational: 256 x 17 ROM + shifter.
// =============================================================================

module exp2neg (
    input  wire [32:0] z,
    output wire [16:0] e
);

    wire [33:0] zr  = {1'b0, z} + 34'd128;
    wire [17:0] ip  = zr[33:16];
    wire [7:0]  idx = zr[15:8];
    reg  [16:0] frac;

    always @(*) begin
        case (idx)""")
for i, v in enumerate(lut):
    print(f"            8'd{i}: frac = 17'd{v};")
print("""            default: frac = 17'd0;
        endcase
    end

    assign e = (ip > 18'd16) ? 17'd0 : (frac >> ip[4:0]);

endmodule""")
